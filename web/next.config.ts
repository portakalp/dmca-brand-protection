import type { NextConfig } from "next";

// Locally the panel and the API share one origin through this rewrite, so the API's session
// cookie works as in prod, where the edge Worker sends /api/* to the api service (§22) and the
// web service never sees those paths. Rewrites are read at build time: the prod image is built
// without API_ORIGIN.
const apiOrigin = process.env.API_ORIGIN;

const securityHeaders = [
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "same-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  output: "standalone",
  poweredByHeader: false,
  // `next dev` would otherwise write an AGENTS.md into web/.
  agentRules: false,
  cacheComponents: true,
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  async rewrites() {
    return apiOrigin ? [{ source: "/api/:path*", destination: `${apiOrigin}/api/:path*` }] : [];
  },
};

export default nextConfig;
